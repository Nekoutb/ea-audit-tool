/**
 * The user-acceptance script: what a firm should exercise before trusting the
 * tool with a real audit, phase by phase, in the order an engagement runs.
 *
 * Grounded in the actual file index (lib/file-index.ts) rather than invented:
 * where a scenario names a task it names a real one — P6.1, S3.1, E1.2, C1.1 —
 * so a tester can find it and an auditor can see the coverage is the firm's own
 * methodology and not a generic checklist.
 *
 * Kept as data so the page can track a verdict and a note against each item and
 * count what is left. `key` is the stable identifier a stored result points at:
 * change the wording freely, never the key, or a tester's answers detach from
 * the question they answered.
 *
 * `path` is a real route. The page turns it into a link so a tester goes
 * straight to the screen; `:id` is replaced with the engagement they select.
 */

export type UatStatus = "not_started" | "passed" | "failed" | "blocked";

export interface UatScenario {
  key: string;
  title: string;
  /** The task code or standard this exercises — E1.2, ISA 240, and so on. */
  ref?: string;
  /** Why an auditor should care. Present where the answer is not obvious. */
  why?: string;
  /** Where to do it; `:id` becomes the selected engagement. */
  path?: string;
  steps: string[];
  expect: string;
}

export interface UatSection {
  key: string;
  title: string;
  intro: string;
  scenarios: UatScenario[];
}

/** Compact source form: [key, title, steps, expect, ref?, path?, why?] */
type Row = [string, string, string[], string, string?, string?, string?];

const rows = (prefix: string, list: Row[]): UatScenario[] =>
  list.map(([key, title, steps, expect, ref, path, why]) => ({
    key: `${prefix}.${key}`,
    title,
    steps,
    expect,
    ref,
    path,
    why,
  }));

