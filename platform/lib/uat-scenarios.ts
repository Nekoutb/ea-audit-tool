export const ALL_SCENARIOS: UatScenario[] = UAT_SECTIONS.flatMap((s) => s.scenarios);

/** Keys are the contract with stored results; a duplicate would silently merge two answers. */
export function duplicateKeys(): string[] {
  const seen = new Set<string>();
  const dupes: string[] = [];
  for (const s of ALL_SCENARIOS) {
    if (seen.has(s.key)) dupes.push(s.key);
    seen.add(s.key);
  }
  return dupes;
}

/** How many scenarios each phase carries — the page shows it, and a test floors it. */
export function sectionCounts(): { key: string; title: string; count: number }[] {
  return UAT_SECTIONS.map((s) => ({ key: s.key, title: s.title, count: s.scenarios.length }));
}
